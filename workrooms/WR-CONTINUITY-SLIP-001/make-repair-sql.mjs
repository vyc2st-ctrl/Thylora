// Builds REPAIR-PACKET.sql from the verbatim source files in the repo.
// Nothing here touches the backend. Applying the output needs the Chairman's yes.
//
// Each insert:
//   - takes the text below the first "---" line of the source file, byte-for-byte
//   - numbers itself from the LIVE custody head at apply time (never a remembered number)
//   - refuses to commit if sha256(stored text) differs from the hash computed here
//   - is skipped if its query_id already exists (re-running is harmless)
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const here = new URL('.', import.meta.url);
const root = new URL('../../', import.meta.url);

function body(path) {
  const raw = readFileSync(path, 'utf8');
  const i = raw.indexOf('\n---\n');
  if (i < 0) throw new Error(`NO_SEPARATOR ${path}`);
  return raw.slice(i + 5);
}

function sha256(s) { return createHash('sha256').update(s, 'utf8').digest('hex'); }

function dollar(text) {
  let tag = 'vyc';
  while (text.includes(`$${tag}$`)) tag += 'x';
  return `$${tag}$${text}$${tag}$`;
}

function insert({ id, label, text, method, sourceApp, restart, refs }) {
  const h = sha256(text);
  return `
-- ${id}: ${label}
-- words: ${text.trim().split(/\s+/).length} · chars: ${[...text].length} · sha256: ${h}
do $do$
declare
  v_text text := ${dollar(text)};
  v_head bigint;
  v_prev text;
begin
  if exists (select 1 from public.thylora_query_carryforward where query_id = '${id}') then
    raise notice 'SKIP ${id} — already present';
    return;
  end if;
  if encode(sha256(convert_to(v_text, 'UTF8')), 'hex') <> '${h}' then
    raise exception 'HASH_MISMATCH ${id}: stored text is not the source text';
  end if;
  select sequence_no, query_id into v_head, v_prev
    from public.thylora_query_carryforward order by sequence_no desc limit 1;
  insert into public.thylora_query_carryforward
    (query_id, source_app, session_label, user_message, message_hash, user_message_hash,
     truth_class, capture_state, capture_method, verbatim_locked, sequence_no,
     previous_query_id, restart_point, continuity_refs, created_by, supersession_state)
  values
    ('${id}', '${sourceApp}', '${label}', v_text, '${h}', '${h}',
     'EARTH_ACTUAL', 'VERBATIM_LOCKED', '${method}', true, v_head + 1,
     v_prev, ${dollar(restart)}, '${JSON.stringify(refs)}'::jsonb,
     'production_executive_repair_packet', 'CURRENT');
  raise notice 'ADD ${id} at sequence %', v_head + 1;
end $do$;
-- read back: select sequence_no, verbatim_locked, length(user_message),
--   encode(sha256(convert_to(user_message,'UTF8')),'hex') = '${h}' as hash_ok
--   from public.thylora_query_carryforward where query_id = '${id}';
`;
}

