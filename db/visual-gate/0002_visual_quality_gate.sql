--     page or illustration is authored here, and no authorship name is invented.
create table if not exists thylora_visual_gate_bindings (
  work_code   text primary key,
  gate_code   text not null default 'THY-VISUAL-QUALITY-GATE-001',
  bound_note  text not null,
  created_at  timestamptz not null default now()
);
insert into thylora_visual_gate_bindings (work_code, gate_code, bound_note) values
 ('THY-WORK-BRAMBLE-PROOF-PRODUCT-544','THY-VISUAL-QUALITY-GATE-001',
  'Bramble is not rebuilt independently of this standard. Any Bramble manuscript or page plan is checked against the recovered exemplars and the 1930s-1940s era lock (THY-VIS-EXEMPLAR-003) before it returns to the Chairman. Authorship for Bramble is OPEN on all six roles; no name is invented to clear the gate.')
on conflict (work_code) do update set
  gate_code = excluded.gate_code, bound_note = excluded.bound_note;

